# shellcheck shell=bash
# Keycloak's admin API over loopback, as the edge's admin service client:
# shared by the realm reconcile (mcp-edge-realm, ./keycloak.nix) and
# `mcp-edge-secrets revoke-all` (./secrets-cli.sh), which both source it.
# Needs curl and jq, and these set:
#   EDGE_KEYCLOAK       Keycloak on loopback (http://127.0.0.1:<port>)
#   EDGE_REALM          the edge's realm
#   EDGE_ADMIN_CLIENT   the admin service client (master realm)
# The secret and the token travel on curl's stdin, never a command line
# (which every local user can read).

# admin_login <secret>: signs in; later calls use the token.
admin_login() {
  admin_token=$(
    curl -sSf --data @- "$EDGE_KEYCLOAK/realms/master/protocol/openid-connect/token" \
      <<< "grant_type=client_credentials&client_id=$EDGE_ADMIN_CLIENT&client_secret=$1" \
      | jq -er .access_token
  )
}

# admin_api <method> <path under the realm> [json body]
admin_api() {
  local method=$1 path=$2 body=${3:-}
  local args=(-sSf -X "$method" --config -)
  [[ -z $body ]] || args+=(-H 'Content-Type: application/json' --data "$body")
  curl "${args[@]}" "$EDGE_KEYCLOAK/admin/realms/$EDGE_REALM$path" \
    <<< "header = \"Authorization: Bearer $admin_token\""
}

# The realm's key providers, one JSON object per line.
key_providers() {
  local realm_id
  realm_id=$(admin_api GET "" | jq -er .id)
  admin_api GET "/components?type=org.keycloak.keys.KeyProvider&parent=$realm_id" | jq -c '.[]'
}

# A provider whose keys Keycloak generated itself (rsa-generated,
# hmac-generated, …): nobody outside holds them. Any other kind (an
# imported key, a keystore) is someone's own key, which no declaration here
# makes, so the edge never keeps one.
is_generated() {
  [[ $(jq -r .providerId <<< "$1") == *-generated ]]
}

# The key ids that sign or verify (active or passive), sorted.
live_kids() {
  admin_api GET /keys | jq -r '.keys[] | select(.status != "DISABLED") | .kid' | sort
}

# Deletes every key provider Keycloak did not generate.
# (Listed first, so a failed listing fails here rather than reading as
# "no providers".)
remove_foreign_key_providers() {
  local providers provider
  providers=$(key_providers)
  while IFS= read -r provider; do
    [[ -n $provider ]] || continue
    is_generated "$provider" && continue
    echo "removing key provider $(jq -r '"\(.name) (\(.providerId))"' <<< "$provider"): not generated by Keycloak" >&2
    admin_api DELETE "/components/$(jq -r .id <<< "$provider")" > /dev/null
  done <<< "$providers"
}
