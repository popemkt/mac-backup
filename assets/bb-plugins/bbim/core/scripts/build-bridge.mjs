// Builds bridge/bbim-bridge.js, the classic script a frame includes to answer
// bbim's hint bridge: src/bridge/auto.ts bundled with its dependencies into
// one minified IIFE. The bundle must contain no `effect` module and stay under
// BRIDGE_BUDGET_BYTES; either failure stops the build. `--check` also fails
// when the committed file is stale instead of writing it.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const core = fileURLToPath(new URL("..", import.meta.url));
const output = `${core}bridge/bbim-bridge.js`;

/** The most the built bridge may weigh: a frame pays for every byte. */
export const BRIDGE_BUDGET_BYTES = 20 * 1024;

/** Why a bundle is unacceptable, from esbuild's metafile; empty when it is fine. */
export function bridgeProblems(text, metafile) {
  const problems = [];
  const effect = Object.keys(metafile.inputs).filter((input) => /(^|\/)node_modules\/(@effect\/[^/]+|effect)\//.test(input));
  if (effect.length > 0) problems.push(`bundles ${effect.length} effect module(s), e.g. ${effect[0]}`);
  const bytes = Buffer.byteLength(text);
  if (bytes > BRIDGE_BUDGET_BYTES) problems.push(`is ${bytes} bytes, over the ${BRIDGE_BUDGET_BYTES}-byte budget`);
  return problems;
}

export async function bundleBridge() {
  const result = await build({
    entryPoints: [`${core}src/bridge/auto.ts`],
    bundle: true,
    minify: true,
    format: "iife",
    platform: "browser",
    target: "es2022",
    legalComments: "none",
    write: false,
    metafile: true,
    banner: {
      js: "/* bbim hint bridge (@popemkt/bbim-core). Generated by core/scripts/build-bridge.mjs from src/bridge; do not edit. */",
    },
  });
  const text = result.outputFiles[0].text;
  const problems = bridgeProblems(text, result.metafile);
  if (problems.length > 0) throw new Error(`bridge/bbim-bridge.js ${problems.join("; ")}`);
  return text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await bundleBridge();
  if (process.argv.includes("--check")) {
    const committed = await readFile(output, "utf8").catch(() => "");
    if (committed !== text) {
      console.error("bridge/bbim-bridge.js is stale: run npm run build:bridge");
      process.exit(1);
    }
  } else {
    await writeFile(output, text);
    console.log(`wrote ${output} (${(text.length / 1024).toFixed(1)} KiB)`);
  }
}
