// Builds the two bridge bundles, each its entry bundled with its dependencies
// into one minified IIFE:
//
// - bridge/bbim-bridge.js, the classic script an iframe includes to answer
//   bbim's hint bridge (src/bridge/auto.ts);
// - bridge/bbim-page.ts, the native-page bridge as a string module a host
//   evaluates in a page it shows in a native view (src/bridge/page-entry.ts).
//
// A bundle must contain no `effect` module and stay under its byte budget;
// either failure stops the build. `--check` also fails when a committed file
// is stale instead of writing it.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const core = fileURLToPath(new URL("..", import.meta.url));

/** The most the built iframe bridge may weigh: a frame pays for every byte. */
export const BRIDGE_BUDGET_BYTES = 20 * 1024;
/** The page bridge also draws labels; it is sent with every request to a page. */
export const PAGE_BUDGET_BYTES = 24 * 1024;

/** Why a bundle is unacceptable, from esbuild's metafile; empty when it is fine. */
export function bridgeProblems(text, metafile, budget = BRIDGE_BUDGET_BYTES) {
  const problems = [];
  const effect = Object.keys(metafile.inputs).filter((input) => /(^|\/)node_modules\/(@effect\/[^/]+|effect)\//.test(input));
  if (effect.length > 0) problems.push(`bundles ${effect.length} effect module(s), e.g. ${effect[0]}`);
  const bytes = Buffer.byteLength(text);
  if (bytes > budget) problems.push(`is ${bytes} bytes, over the ${budget}-byte budget`);
  return problems;
}

async function bundle(entry, name, budget, banner) {
  const result = await build({
    entryPoints: [`${core}${entry}`],
    bundle: true,
    minify: true,
    format: "iife",
    platform: "browser",
    target: "es2022",
    legalComments: "none",
    write: false,
    metafile: true,
    ...(banner === undefined ? {} : { banner: { js: banner } }),
  });
  const text = result.outputFiles[0].text;
  const problems = bridgeProblems(text, result.metafile, budget);
  if (problems.length > 0) throw new Error(`${name} ${problems.join("; ")}`);
  return text;
}

export function bundleBridge() {
  return bundle(
    "src/bridge/auto.ts",
    "bridge/bbim-bridge.js",
    BRIDGE_BUDGET_BYTES,
    "/* bbim hint bridge (@popemkt/bbim-core). Generated by core/scripts/build-bridge.mjs from src/bridge; do not edit. */",
  );
}

/** bridge/bbim-page.ts: the page bundle as a TypeScript string constant. */
export async function bundlePage() {
  const script = await bundle("src/bridge/page-entry.ts", "bridge/bbim-page.ts", PAGE_BUDGET_BYTES);
  return [
    "// bbim native-page bridge (@popemkt/bbim-core). Generated by core/scripts/build-bridge.mjs",
    "// from src/bridge/page-entry.ts; do not edit. Evaluate it in the page's isolated world.",
    `export const BBIM_PAGE_SCRIPT: string = ${JSON.stringify(script.trimEnd())};`,
    "",
  ].join("\n");
}

/** Every generated file and its fresh content. */
export async function bundles() {
  return [
    { path: `${core}bridge/bbim-bridge.js`, text: await bundleBridge() },
    { path: `${core}bridge/bbim-page.ts`, text: await bundlePage() },
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const built = await bundles();
  if (process.argv.includes("--check")) {
    const committed = await Promise.all(built.map(({ path }) => readFile(path, "utf8").catch(() => "")));
    const stale = built.filter(({ text }, index) => committed[index] !== text);
    for (const { path } of stale) console.error(`${path} is stale: run npm run build:bridge`);
    if (stale.length > 0) process.exit(1);
  } else {
    await Promise.all(built.map(({ path, text }) => writeFile(path, text)));
    for (const { path, text } of built) console.log(`wrote ${path} (${(text.length / 1024).toFixed(1)} KiB)`);
  }
}
