/**
 * A seeded random sequence (mulberry32): the same seed always lays the same
 * scatter, so a study looks the same on every mount. Plain arithmetic; a
 * study draws from it while it builds, never per frame.
 */
export function seededRandom(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 0x1_0000_0000;
  };
}
